import { FormEvent, useEffect, useState } from "react";
import { Bot, Send, Sparkles, UserRound } from "lucide-react";
import { Card } from "../components/ui/Card";
import {
  ApiRequestError,
  askAiQuestion,
  getAiStatus,
  type AiStatus,
} from "../services/api";

interface ChatMessage {
  id: number;
  role: "assistant" | "user";
  content: string;
}

const SUGGESTED_QUESTIONS = [
  "Which orders are pending?",
  "Summarize this week's paid sales.",
  "Which items sold the most?",
];

export function AIAssistant() {
  const [status, setStatus] = useState<AiStatus | null>(null);
  const [statusError, setStatusError] = useState<string | null>(null);
  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      id: 0,
      role: "assistant",
      content: "Hi! I can answer questions about the current demo orders and the last seven days of sales.",
    },
  ]);
  const [question, setQuestion] = useState("");
  const [isLoadingStatus, setIsLoadingStatus] = useState(true);
  const [isSending, setIsSending] = useState(false);

  useEffect(() => {
    let active = true;
    getAiStatus()
      .then((result) => {
        if (active) setStatus(result);
      })
      .catch((error: unknown) => {
        if (active) {
          setStatusError(error instanceof Error ? error.message : "Could not check AI configuration.");
        }
      })
      .finally(() => {
        if (active) setIsLoadingStatus(false);
      });

    return () => {
      active = false;
    };
  }, []);

  async function sendQuestion(text = question) {
    const message = text.trim();
    if (!message || isSending || !status?.configured) return;

    setMessages((current) => [...current, { id: Date.now(), role: "user", content: message }]);
    setQuestion("");
    setIsSending(true);

    try {
      const result = await askAiQuestion(message);
      setMessages((current) => [
        ...current,
        { id: Date.now() + 1, role: "assistant", content: result.answer },
      ]);
    } catch (error) {
      const safeMessage = error instanceof ApiRequestError &&
        error.code === "AI_TEMPORARILY_UNAVAILABLE"
        ? "The AI service is busy right now, please try again in a minute."
        : error instanceof Error
          ? error.message.replace(/^API error \d+: /, "")
          : "The AI request could not be completed. Please try again.";
      setMessages((current) => [
        ...current,
        { id: Date.now() + 1, role: "assistant", content: safeMessage },
      ]);
    } finally {
      setIsSending(false);
    }
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void sendQuestion();
  }

  const ready = Boolean(status?.configured);

  return (
    <div className="page-stack">
      <div className="welcome-row">
        <div>
          <h2>AI Assistant</h2>
          <p>Ask about the current demo orders and seven-day sales summary.</p>
        </div>
        <span className="demo-pill">
          <Sparkles size={14} /> {isLoadingStatus ? "Checking…" : ready ? "API key detected" : "Setup required"}
        </span>
      </div>

      <Card className="assistant-card assistant-chat">
        <div className="assistant-chat-heading">
          <div className="assistant-icon"><Bot size={26} /></div>
          <div>
            <h2>PayPilot AI</h2>
            <p>
              Powered by Google Gemini{status?.model ? ` (${status.model})` : ""} · Uses sample order data
            </p>
          </div>
        </div>

        <div className="demo-notice" role="note">
          Responses are generated by Google Gemini using the current server-side demo orders and derived sales totals. Customer emails are not sent. Do not enter sensitive customer or payment information.
        </div>

        {isLoadingStatus && <p className="stat-change">Checking server AI configuration…</p>}
        {statusError && <p className="paypal-message paypal-message--error" role="alert">{statusError}</p>}
        {status && !status.configured && (
          <p className="paypal-message" role="status">{status.message} Get a key from <a href="https://aistudio.google.com/apikey" target="_blank" rel="noreferrer">Google AI Studio</a>, add it to the project root `.env`, then restart the backend.</p>
        )}

        <div className="chat-messages" role="log" aria-live="polite" aria-label="Conversation">
          {messages.map((message) => (
            <div key={message.id} className={`chat-message chat-message--${message.role}`}>
              <span className="chat-message-avatar" aria-hidden="true">
                {message.role === "assistant" ? <Bot size={16} /> : <UserRound size={16} />}
              </span>
              <p>{message.content}</p>
            </div>
          ))}
          {isSending && (
            <div className="chat-message chat-message--assistant">
              <span className="chat-message-avatar" aria-hidden="true"><Bot size={16} /></span>
              <p role="status">Thinking…</p>
            </div>
          )}
        </div>

        {ready && (
          <div className="chat-suggestions" aria-label="Suggested questions">
            {SUGGESTED_QUESTIONS.map((suggestion) => (
              <button
                key={suggestion}
                type="button"
                className="prompt-chip"
                disabled={isSending}
                onClick={() => void sendQuestion(suggestion)}
              >
                {suggestion}
              </button>
            ))}
          </div>
        )}

        <form className="assistant-input" onSubmit={handleSubmit}>
          <label className="sr-only" htmlFor="assistant-message">Ask PayPilot AI a question</label>
          <textarea
            id="assistant-message"
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            placeholder={ready ? "Ask about orders or sales…" : "Configure the backend AI key to start chatting"}
            maxLength={1000}
            rows={2}
            disabled={!ready || isSending}
          />
          <button type="submit" aria-label="Send question" disabled={!ready || isSending || !question.trim()}>
            <Send size={16} /> <span>Send</span>
          </button>
        </form>
        <p className="chat-footnote">Answers are based on demo data and may not reflect live transactions.</p>
      </Card>
    </div>
  );
}
